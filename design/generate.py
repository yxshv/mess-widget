"""Generates the widget's drawables.

Meal illustrations are Microsoft Fluent Emoji (flat style, MIT; see
design/fluent-emoji/). Card gradients follow the time of day, after Samsung
Weather. Run `python3 design/generate.py` to regenerate res/drawable/art_*.xml,
card_*.xml and the launcher icon foreground.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
EMOJI = os.path.join(HERE, "fluent-emoji")

# meal: (emoji file, card gradient top, bottom)
MEALS = {
    "breakfast": ("flatbread_flat.svg", "#EE8358", "#F4AE6A"),   # sunrise
    "lunch": ("curry_rice_flat.svg", "#3B78C8", "#5E9BDA"),      # midday sky
    "snacks": ("hot_beverage_flat.svg", "#3C9C8C", "#6DB8A2"),   # afternoon
    "dinner": ("pot_of_food_flat.svg", "#283766", "#46578C"),    # night
}
ICON_EMOJI = "curry_rice_flat.svg"
ICON_BG = "#4A88D0"


def svg_paths(name):
    """(pathData, fill) pairs from a Fluent flat SVG (they use only <path d fill>)."""
    text = open(os.path.join(EMOJI, name)).read()
    return re.findall(r'<path d="([^"]+)" fill="([^"]+)"', text)


def vector(paths, size, viewport=32, inset=0.0):
    scale = (viewport - 2 * inset) / viewport
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by design/generate.py from Microsoft Fluent Emoji (MIT). -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{size}dp" android:height="{size}dp"',
           f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">',
           f'    <group android:translateX="{inset}" android:translateY="{inset}"'
           f' android:scaleX="{scale:.4f}" android:scaleY="{scale:.4f}">']
    for d, fill in paths:
        out.append(f'        <path android:fillColor="{fill}" android:pathData="{d}" />')
    out += ["    </group>", "</vector>"]
    return "\n".join(out) + "\n"


def card(top, bottom):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/generate.py; edit there. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="270" android:startColor="{top}" android:endColor="{bottom}" />
    <corners android:radius="28dp" />
</shape>
'''


if __name__ == "__main__":
    drawable = os.path.join(HERE, "..", "app", "src", "main", "res", "drawable")
    for meal, (emoji, top, bottom) in MEALS.items():
        open(os.path.join(drawable, f"art_{meal}.xml"), "w").write(vector(svg_paths(emoji), 120))
        open(os.path.join(drawable, f"card_{meal}.xml"), "w").write(card(top, bottom))
    # Adaptive icon: emoji in the middle 66dp of 108dp (inset 32 * 21/108 units).
    open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w").write(
        vector(svg_paths(ICON_EMOJI), 108, inset=32 * 21 / 108))
